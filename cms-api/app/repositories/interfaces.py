"""Puertos de persistencia; las reglas pertenecen a los servicios."""

from typing import Protocol
from uuid import UUID

from app.domain.enums import DocumentContentType, DocumentStatus, TemplateTargetType
from app.infrastructure.database.models.document import DocumentModel
from app.infrastructure.database.models.template import TemplateModel


class TemplateRepository(Protocol):
    def lock_catalog(self) -> None: ...
    def get_by_id(self, template_id: UUID) -> TemplateModel | None: ...
    def get_by_name(self, name: str) -> TemplateModel | None: ...
    def count(self) -> int: ...
    def get_default(self) -> TemplateModel | None: ...
    def list_all(self, target_type: TemplateTargetType | None = None) -> list[TemplateModel]: ...
    def create(self, template: TemplateModel) -> None: ...
    def update(self, template: TemplateModel) -> None: ...
    def delete(self, template: TemplateModel) -> None: ...
    def count_documents_using_template(self, template_id: UUID) -> int: ...


class DocumentRepository(Protocol):
    def get_by_id(self, document_id: UUID, *, for_update: bool = False) -> DocumentModel | None: ...
    def get_by_slug(self, slug: str) -> DocumentModel | None: ...
    def list_all(self, content_type: DocumentContentType | None = None, status: DocumentStatus | None = None) -> list[DocumentModel]: ...
    def get_templates(self, template_ids: set[UUID]) -> dict[UUID, TemplateModel]: ...
    def create(self, document: DocumentModel) -> None: ...
    def update(self, document: DocumentModel) -> None: ...
    def delete(self, document: DocumentModel) -> None: ...
