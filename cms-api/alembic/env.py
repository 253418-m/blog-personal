"""Entorno Alembic con metadatos completos y URL fuera del archivo INI."""

from logging.config import fileConfig

from alembic import context

from app.infrastructure.database.base import Base
from app.infrastructure.database import models  # noqa: F401: registrar todas las tablas
from app.infrastructure.database.session import engine


config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Genera SQL PostgreSQL sin conectarse al servidor."""
    context.configure(
        url=engine.url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Aplica migraciones al destino DATABASE_URL configurado explícitamente."""
    try:
        with engine.connect() as connection:
            context.configure(
                connection=connection,
                target_metadata=target_metadata,
                compare_type=True,
            )
            with context.begin_transaction():
                context.run_migrations()
    finally:
        engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
